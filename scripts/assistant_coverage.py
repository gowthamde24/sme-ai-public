"""A1 of job assistant-does-the-work: the coverage table, generated from the LIVE route list (never typed). Writes docs/assistant-tools-coverage.md and prints the numbers.

Run from services/ai-api:  PYTHONPATH=$PWD python ../../scripts/assistant_coverage.py [--check]
--check: fail when the committed table is not what the routes give today (a route was added or changed without the table)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "ai-api"))

from app.assistant_tools import catalog  # noqa: E402
from app.config import Settings  # noqa: E402
from app.main import create_app  # noqa: E402

OUT = ROOT / "docs" / "assistant-tools-coverage.md"
REASON_WORDS = {
    "real_data_gate": "the real-data gate: always a screen and the owner",
    "billing": "billing changes: always a screen and the owner",
    "workspace_deletion": "deleting the workspace: always a screen and the owner",
    "erasure": "erasing a person's data: a person decides, with a reason",
    "assistant_itself": "the assistant's own chat and voice doors",
    "internal": "the worker's and the agent runtime's own doors",
    "binary_upload": "a file's bytes: they come in through the chat's file drop (A2)",
    "developer_keys": "an API key: its secret is shown once, on the screen (Settings -> Developers), never in the chat",
}


def render() -> tuple[str, dict[str, object]]:
    app = create_app(Settings(_env_file=None, api_env="development"))  # type: ignore[call-arg]
    decisions = catalog.decide(catalog.operations(app.openapi()))
    cov = catalog.coverage(decisions)
    lines = [
        "# Assistant tools: the coverage table (A1)",
        "",
        "Generated by `scripts/assistant_coverage.py` from the live route list (`app/assistant_tools/catalog.py` decides each operation); do not edit by hand. Job assistant-does-the-work, owner decision 4 Nov 2026.",
        "",
        f"**{cov['operations']} operations** under `/v1/tenants/{{tenant_id}}`: **{cov['tools']} tools**, {cov['screen_only']} screen only ({cov['forbidden']} of them forbidden for the assistant). "
        f"**Tools are {cov['tool_share_of_not_forbidden']}% of the non-forbidden operations** (target 90%). Write tools: {cov['write_tools']}, of which {cov['write_tools_with_undo']} declare an undo.",
        "",
        "Levels: " + ", ".join(f"{k} {v}" for k, v in cov["tools_by_level"].items()) + ".  Screen only: " + ", ".join(f"{k} {v}" for k, v in cov["screen_only_by_reason"].items()) + ".",
        "",
        "| Tool or screen | Method | Path (after the tenant) | Level | Undo | What the route does |",
        "|---|---|---|---|---|---|",
    ]
    for d in sorted(decisions, key=lambda d: (catalog.area(d.op.path), catalog.tail(d.op.path), d.op.method)):
        what = d.op.summary.replace("|", "/")
        if d.tool:
            level = d.level if d.level != "sensitive" else f"sensitive ({d.sensitive})"
            undo = "" if d.level == "read" else (f"{d.undo} ({d.undo_via})" if d.undo != "none" else "none")
            lines.append(f"| `{d.op.name}` | {d.op.method} | `{catalog.tail(d.op.path)}` | {level} | {undo} | {what} |")
        else:
            lines.append(f"| screen only: {REASON_WORDS[str(d.screen_only)]} | {d.op.method} | `{catalog.tail(d.op.path)}` | | | {what} |")
    return "\n".join(lines) + "\n", cov


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, cov = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/assistant-tools-coverage.md is stale: run scripts/assistant_coverage.py", file=sys.stderr)
            return 1
    else:
        OUT.write_text(text, encoding="utf-8")
    print(json.dumps(cov))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
