"""Write the migration that puts the plans catalogue into the database (job DI, ADR 0092), the way pack data is synced (scripts/pack_migration.py).

  python3 scripts/plans_migration.py                  write supabase/migrations/<stamp>_di_plans_data.sql for a catalogue version no earlier migration has synced
  python3 scripts/plans_migration.py --check          write nothing; exit 1 when the version in packages/plans/plans.json is not in a migration yet (CI runs this through make plans-check)
  make plans-migration

A migration on main is append-only, so a catalogue VERSION that was synced is never edited (the script refuses: change the plans and raise `version`). Every synced version carries a marker comment
(`-- plans-sync: <version> <sha256>`) that this script reads back. The manifest stored in the database is plans.json without its `$schema` line; its SHA-256 is taken over the canonical JSON (sorted keys, no
spaces, UTF-8), so the test and this script agree on the same bytes."""

# ruff: noqa: S608 - this script WRITES a migration file from reviewed JSON; it executes no SQL

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import plans_check as pc  # noqa: E402

ROOT = pc.ROOT
MIGRATIONS = ROOT / "supabase" / "migrations"
MARK = re.compile(r"^-- plans-sync: (\d+) ([0-9a-f]{64})\s*$", re.M)


def manifest_of(cat: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in cat.items() if k != "$schema"}


def canonical(manifest: dict[str, Any]) -> str:
    return json.dumps(manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def manifest_sha256(manifest: dict[str, Any]) -> str:
    return hashlib.sha256(canonical(manifest).encode("utf-8")).hexdigest()


def synced(migrations_dir: Path = MIGRATIONS) -> dict[int, str]:
    out: dict[int, str] = {}
    for path in sorted(migrations_dir.glob("*.sql")):
        for version, sha in MARK.findall(path.read_text(encoding="utf-8")):
            out[int(version)] = sha
    return out


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def pending(plans_dir: Path = pc.PLANS, migrations_dir: Path = MIGRATIONS) -> tuple[dict[str, Any] | None, list[str]]:
    """(the catalogue to sync or None, problems)"""
    cat = pc.load_catalogue(plans_dir)
    sha = manifest_sha256(manifest_of(cat))
    done = synced(migrations_dir)
    version = cat["version"]
    if version in done:
        if done[version] != sha:
            return None, [f"plans.json: version {version} was already synced with different content: a catalogue version is never edited, raise `version` instead"]
        return None, []
    if done and version < max(done):
        return None, [f"plans.json: version {version} is older than the synced version {max(done)}"]
    return cat, []


def render(cat: dict[str, Any]) -> str:
    manifest = manifest_of(cat)
    sha = manifest_sha256(manifest)
    body = json.dumps(manifest, sort_keys=True, indent=1, ensure_ascii=False)
    if "$plans_json$" in body:
        raise SystemExit("plans.json must not contain the text $plans_json$")
    trial = cat["trial"]
    lines = [
        "-- Job DI: the plans catalogue, GENERATED by scripts/plans_migration.py from packages/plans/plans.json. Do not edit by hand; to change a plan, raise `version` and run `make plans-migration`.",
        "-- The marker below is read back by the script and by tests (the manifest in the database must be the one in the repository, byte for byte).",
        f"-- plans-sync: {cat['version']} {sha}",
        "insert into billing.plans (id) values " + ", ".join(f"({_q(p['id'])})" for p in cat["plans"]) + " on conflict do nothing;",
        "insert into billing.catalogue_versions (version, status, trial_plan, trial_days, payment_method_at_start, grace_days, manifest, manifest_sha256) values",
        f"  ({cat['version']}, {_q(cat['status'])}, {_q(trial['plan'])}, {trial['days']}, {'true' if trial['payment_method_at_start'] else 'false'}, {trial['grace_days_after_failed_payment']}, "
        f"$plans_json${body}$plans_json$::jsonb, {_q(sha)});",
        "insert into billing.plan_versions (catalogue_version, plan_id, kind, sort, name, price_paise_monthly, price_paise_per_minute, price_paise_per_message, call_minutes, whatsapp_messages, users, workspaces)",
        "select v.version, p ->> 'id', p ->> 'kind', (p ->> 'sort')::integer, p -> 'name', (p ->> 'price_paise_monthly')::integer, (p ->> 'price_paise_per_minute')::integer, (p ->> 'price_paise_per_message')::integer,",
        "       (p -> 'allowances' ->> 'call_minutes')::integer, (p -> 'allowances' ->> 'whatsapp_messages')::integer, (p -> 'limits' ->> 'users')::integer, (p -> 'limits' ->> 'workspaces')::integer",
        f"  from billing.catalogue_versions v, jsonb_array_elements(v.manifest -> 'plans') p where v.version = {cat['version']};",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stamp", default=None)
    ap.add_argument("--name", default="di_plans_data")
    args = ap.parse_args(argv)
    cat, problems = pending()
    if problems:
        print("\n".join(problems))
        return 1
    if cat is None:
        print("the plans catalogue is in sync with the migrations")
        return 0
    if args.check:
        print(f"not in a migration yet: plans catalogue version {cat['version']}. Run: make plans-migration")
        return 1
    stamp = args.stamp or datetime.now(UTC).strftime("%Y%m%d%H%M%S")
    path = MIGRATIONS / f"{stamp}_{args.name}.sql"
    if path.exists():
        print(f"{path} exists already")
        return 1
    path.write_text(render(cat), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}: plans catalogue version {cat['version']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
