#!/usr/bin/env python3
"""Writes the drafts-only backfill migration of the WhatsApp message catalogue (planner, 19-20 Nov 2026; reports/template-catalogue.md): the 12 catalogue messages that are not part of the first set of 9, in English and
Telugu, as DRAFTS for every business that already has the first set (it has lead_ack). The words come from services/ai-api/app/whatsapp/data/first_templates.json, so they can never differ from what the API creates for a
new business (a test compares them). Idempotent, never submitted to Meta.

  python3 scripts/gen_catalogue_backfill.py > supabase/migrations/<number>_catalogue_backfill.sql
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "services" / "ai-api"))
from app.whatsapp import first_templates

FIRST_SET = {"lead_ack", "visit_reminder", "visit_confirmation", "missed_call_followup", "followup_nudge", "catalogue_share", "new_collection_offer", "festival_offer", "continue_chat"}


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def main() -> None:
    rows = [d for d in first_templates.drafts(("en", "te")) if d["name"] not in FIRST_SET]
    values = ",\n".join(f"  ({q(d['name'])}, {q(d['language'])}, {q(d['category'])}, {q(d['purpose'])}, {q(d['body'])}, {q(d['opt_out_label'])})" for d in rows)
    print(f"""-- The WhatsApp message catalogue for businesses that already have the first set (planner, 19-20 Nov 2026; reports/template-catalogue.md): the {len({d['name'] for d in rows})} catalogue messages that are not in the first set, in English and
-- Telugu, as DRAFTS for every business that has the first set (it has lead_ack), and nothing else: never submitted to Meta (the Owner presses "Send drafts to WhatsApp for review" himself, one second step), idempotent
-- (an existing row, in any status, is left as it is), ids exactly as the API makes them (uuid v5 of tenant|name|language). Generated by scripts/gen_catalogue_backfill.py from first_templates.json (a test compares).

insert into integrations.wa_templates (id, tenant_id, name, language, category, purpose, body, opt_out_label, status)
select extensions.uuid_generate_v5('{first_templates.NAMESPACE}'::uuid, t.tenant_id::text || '|' || v.name || '|' || v.language), t.tenant_id, v.name, v.language, v.category, v.purpose, v.body, nullif(v.opt_out_label, ''), 'draft'
  from (select distinct tenant_id from integrations.wa_templates where name = 'lead_ack') t
 cross join (values
{values}
) as v(name, language, category, purpose, body, opt_out_label)
on conflict do nothing;""")


if __name__ == "__main__":
    main()
