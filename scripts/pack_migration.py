"""Write the migration that puts pack data into the database (job CK, blueprint section 13).

  python3 scripts/pack_migration.py                       write supabase/migrations/<now>_ck_pack_data.sql for every module and pack version that no earlier migration has synced
  python3 scripts/pack_migration.py --stamp 20261122090100 --name ck_packs_data     choose the file name (the job's own first file)
  python3 scripts/pack_migration.py --check               write nothing; exit 1 when a module or a pack in packages/packs is not in a migration yet (CI runs this through make packs-check)
  make pack-migration

A migration on main is append-only, so packs follow the same rule: a pack VERSION that was synced is never edited (the script refuses: change the pack and raise its version), and a new version or a
new pack is a NEW migration. Every synced module and pack carries a marker comment (`-- module-sync: <code>`, `-- pack-sync: <id> <version> <sha256> <default|->`) that this script reads back.
The manifest stored in the database is the pack.json content without its `$schema` line; its SHA-256 is taken over the canonical JSON (sorted keys, no spaces, UTF-8), so the integration test and this
script agree on the same bytes."""

# ruff: noqa: S608 - this script WRITES a migration file from reviewed JSON; it executes no SQL

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import packs_check as pc  # noqa: E402

ROOT = pc.ROOT
MIGRATIONS = ROOT / "supabase" / "migrations"
MODULE_MARK = re.compile(r"^-- module-sync: ([a-z][a-z0-9_]*)\s*$", re.M)
PACK_MARK = re.compile(r"^-- pack-sync: ([a-z][a-z0-9_]*) (\d+) ([0-9a-f]{64}) (default|-)\s*$", re.M)


def manifest_of(pack: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in pack.items() if k != "$schema"}


def canonical(manifest: dict[str, Any]) -> str:
    return json.dumps(manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def manifest_sha256(manifest: dict[str, Any]) -> str:
    return hashlib.sha256(canonical(manifest).encode("utf-8")).hexdigest()


def synced(migrations_dir: Path = MIGRATIONS) -> tuple[set[str], dict[tuple[str, int], tuple[str, bool]]]:
    modules: set[str] = set()
    packs: dict[tuple[str, int], tuple[str, bool]] = {}
    for path in sorted(migrations_dir.glob("*.sql")):
        text = path.read_text(encoding="utf-8")
        modules.update(MODULE_MARK.findall(text))
        for code, version, sha, default in PACK_MARK.findall(text):
            packs[(code, int(version))] = (sha, default == "default")
    return modules, packs


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def pending(packs_dir: Path = pc.PACKS, migrations_dir: Path = MIGRATIONS) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[str]]:
    """(modules to sync, packs to sync, problems)"""
    done_modules, done_packs = synced(migrations_dir)
    problems: list[str] = []
    mods = [m for m in pc.load_json(packs_dir / "modules.json")["modules"] if m["code"] not in done_modules]
    todo: list[dict[str, Any]] = []
    for name, pack in pc.load_packs(packs_dir).items():
        manifest = manifest_of(pack)
        sha = manifest_sha256(manifest)
        key = (pack["id"], pack["version"])
        if key in done_packs:
            if done_packs[key][0] != sha:
                problems.append(f"{name}: version {pack['version']} was already synced with different content: a pack version is never edited, raise `version` instead")
            continue
        todo.append(pack)
    return mods, todo, problems


def render(mods: list[dict[str, Any]], packs: list[dict[str, Any]], migrations_dir: Path = MIGRATIONS) -> str:
    _, done_packs = synced(migrations_dir)
    lines = [
        "-- Job CK: pack data, GENERATED by scripts/pack_migration.py from packages/packs (modules.json and each pack.json). Do not edit by hand; to change a pack, raise its `version` and run `make pack-migration`.",
        "-- The markers below are read back by the script and by tests/integration/test_ck_packs_db.py (the manifest in the database must be the one in the repository, byte for byte).",
        "",
    ]
    for m in mods:
        lines += [
            f"-- module-sync: {m['code']}",
            "insert into packs.modules (code, exists_today, guard, description) values "
            f"({_q(m['code'])}, {'true' if m['exists_today'] else 'false'}, {_q(m['guard'])}, {_q(m['description'])});",
            "",
        ]
    default_now = any(d for _, d in done_packs.values())
    for pack in packs:
        manifest = manifest_of(pack)
        sha = manifest_sha256(manifest)
        is_default = bool(pack.get("default_for_existing_workspaces"))
        body = json.dumps(manifest, sort_keys=True, indent=1, ensure_ascii=False)
        if "$pack_json$" in body:
            raise SystemExit("a pack must not contain the text $pack_json$")
        lines.append(f"-- pack-sync: {pack['id']} {pack['version']} {sha} {'default' if is_default else '-'}")
        if is_default and default_now:
            lines.append("update packs.pack_versions set is_default = false where is_default;")
        reviewed = _q(pack["reviewed_by"]) if pack.get("reviewed_by") else "null"
        lines += [
            "insert into packs.pack_versions (code, version, status, is_default, reviewed_by, manifest, manifest_sha256) values",
            f"  ({_q(pack['id'])}, {pack['version']}, {_q(pack['status'])}, {'true' if is_default else 'false'}, {reviewed}, $pack_json${body}$pack_json$::jsonb, {_q(sha)});",
            f"insert into packs.pack_modules (code, version, module) select {_q(pack['id'])}, {pack['version']}, m from jsonb_array_elements_text("
            f"(select v.manifest -> 'modules' from packs.pack_versions v where v.code = {_q(pack['id'])} and v.version = {pack['version']})) as m;",
            "",
        ]
        default_now = default_now or is_default
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stamp", default=None)
    ap.add_argument("--name", default="ck_pack_data")
    args = ap.parse_args(argv)
    mods, packs, problems = pending()
    if problems:
        print("\n".join(problems))
        return 1
    if not mods and not packs:
        print("packs and modules are in sync with the migrations")
        return 0
    if args.check:
        print("not in a migration yet: modules " + ", ".join(m["code"] for m in mods) + "; packs " + ", ".join(f"{p['id']} v{p['version']}" for p in packs) + ". Run: make pack-migration")
        return 1
    stamp = args.stamp or datetime.now(UTC).strftime("%Y%m%d%H%M%S")
    path = MIGRATIONS / f"{stamp}_{args.name}.sql"
    if path.exists():
        print(f"{path} exists already")
        return 1
    path.write_text(render(mods, packs), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}: modules {[m['code'] for m in mods]}, packs {[(p['id'], p['version']) for p in packs]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
