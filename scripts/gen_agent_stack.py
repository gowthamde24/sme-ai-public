#!/usr/bin/env python3
"""Generate the AGENT stack's Supabase config from the owner's (job BG, docs/runbooks/two-local-stacks.md).

The owner's demo runs on the default local stack (supabase/config.toml, project `sme-ai`, ports 543x1). Agents test on a SECOND, fully separate stack: its own project id (so its own containers and its own
Docker volumes) and its own ports (the owner's plus 100). Everything else is the owner's configuration, unchanged, so the two stacks behave the same. This script writes
stacks/sme-ai-agent/supabase/config.toml from supabase/config.toml by the substitutions below and nothing else; `--check` fails if the committed file differs (tests/test_stacks.py runs it).

The agent stack's `migrations`, `tests` and `templates` are COPIES of the owner's (the Supabase CLI refuses a link that leaves the project folder), made by `--sync` before every start, reset and test, and git-ignored: there is one
source of truth (supabase/), never two.

  python3 scripts/gen_agent_stack.py          write the config file
  python3 scripts/gen_agent_stack.py --check  exit 1 if the committed file is out of date
  python3 scripts/gen_agent_stack.py --sync   write the config if stale and copy migrations, tests and templates from supabase/ (scripts/sb does this before start, db, test)
  python3 scripts/gen_agent_stack.py --ensure write the config if stale, copy nothing (scripts/sb does this for status and the like)
"""

from __future__ import annotations

import fcntl
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OWNER = ROOT / "supabase" / "config.toml"
STACK_DIR = ROOT / "stacks" / "sme-ai-agent"  # the folder is named like the project id: the Supabase CLI names its containers and network by the folder for some commands
AGENT = STACK_DIR / "supabase" / "config.toml"

PROJECT_ID = "sme-ai-agent"
# (section, key) -> (the owner's value, the agent stack's value)
CHANGES: dict[tuple[str, str], tuple[str, str]] = {
    ("", "project_id"): ('"sme-ai"', f'"{PROJECT_ID}"'),
    ("api", "port"): ("54321", "54421"),
    ("db", "port"): ("54322", "54422"),
    ("db", "shadow_port"): ("54320", "54420"),
    ("db.pooler", "port"): ("54329", "54429"),
    ("studio", "enabled"): ("true", "false"),  # the dashboard (and pg_meta) are not needed for tests, and they cost memory
    ("studio", "port"): ("54323", "54423"),
    ("local_smtp", "port"): ("54324", "54424"),
    ("analytics", "port"): ("54327", "54427"),
    ("edge_runtime", "inspector_port"): ("8083", "8183"),
    ("auth", "site_url"): ('"http://localhost:3000"', '"http://localhost:3001"'),
    ("auth", "additional_redirect_urls"): (
        '["https://127.0.0.1:3000", "http://127.0.0.1:3000"]',
        '["http://127.0.0.1:3001", "http://localhost:3001", "http://127.0.0.1:3002", "http://localhost:3002"]',
    ),
}
HEADER = """# GENERATED by scripts/gen_agent_stack.py from supabase/config.toml: do not edit by hand (tests/test_stacks.py fails if it is out of date).
# This is the AGENT test stack (job BG): its own project id, its own containers and volumes, its own ports (the owner's plus 100). The owner's demo stack is supabase/config.toml.
# Start it with `make agent-db-up`. See docs/runbooks/two-local-stacks.md.
"""


def generate(source: str) -> str:
    seen: set[tuple[str, str]] = set()
    section = ""
    out: list[str] = []
    for line in source.splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]") and not stripped.startswith("[["):
            section = stripped[1:-1]
        elif "=" in stripped and not stripped.startswith("#"):
            key, _, value = stripped.partition("=")
            key = key.strip()
            change = CHANGES.get((section, key))
            if change is not None:
                if value.strip() != change[0]:
                    raise SystemExit(
                        f"supabase/config.toml: [{section or 'top'}] {key} is {value.strip()}, expected {change[0]}: update scripts/gen_agent_stack.py"
                    )
                line = f"{key} = {change[1]}"
                seen.add((section, key))
        out.append(line)
    missing = set(CHANGES) - seen
    if missing:
        raise SystemExit(f"supabase/config.toml no longer has {sorted(missing)}: update scripts/gen_agent_stack.py")
    return HEADER + "\n".join(out) + "\n"


SYNCED = ("migrations", "tests")
# Job CN: `templates` is synced IN PLACE, never replaced. The Supabase CLI hands Kong the mail template as a bind mount of the single FILE (kong:/home/kong/templates/email/confirmation.html); a mount follows the
# file's inode, so a folder that is rebuilt and renamed into place (what migrations and tests are fine with: nothing mounts them) leaves Kong holding a deleted file, the stack's sign-up mail gets the stock link and
# the sign-up tests fail after every `db reset` until Kong is restarted by hand. A file whose bytes are already right is not touched at all; a changed file is rewritten through the same inode.
IN_PLACE = ("templates",)


def sync_in_place(source: Path, target: Path) -> None:
    """Make `target` an exact copy of `source` WITHOUT replacing any file or folder that is already right: same bytes -> untouched; other bytes -> rewritten through the same inode; a file that is gone from
    the source is removed (and an emptied folder); a missing file or folder is created."""
    if target.is_symlink() or target.is_file():
        target.unlink()
    target.mkdir(parents=True, exist_ok=True)
    wanted = {p.relative_to(source) for p in source.rglob("*") if p.is_file()}
    for rel in sorted(wanted):
        src, dst = source / rel, target / rel
        data = src.read_bytes()
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.is_symlink():
            dst.unlink()
        elif dst.is_dir():
            shutil.rmtree(dst)
        if not dst.exists():
            dst.write_bytes(data)
        elif dst.read_bytes() != data:
            with open(dst, "r+b") as handle:  # r+b keeps the inode; "wb" would too, but this never leaves an empty file visible longer than the write
                handle.write(data)
                handle.truncate()
    for path in sorted(target.rglob("*"), key=lambda p: len(p.parts), reverse=True):
        if path.is_file() or path.is_symlink():
            if path.relative_to(target) not in wanted:
                path.unlink()
        elif path.is_dir() and not any(path.iterdir()):
            path.rmdir()


def sync() -> None:
    """Make stacks/sme-ai-agent/supabase/{migrations,tests,templates} exact copies of supabase/ (a deleted migration disappears too). Two callers at once (the API and the web of one run both ask for the
    stack's status) must not trample each other: an exclusive lock serialises them, and each copy is made beside the target and renamed into place, so nobody ever sees a half-copied folder."""
    AGENT.parent.mkdir(parents=True, exist_ok=True)
    with open(AGENT.parent / ".sync.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        for name in SYNCED:
            source, target = ROOT / "supabase" / name, AGENT.parent / name
            staging = AGENT.parent / f".{name}.new"
            if staging.exists():
                shutil.rmtree(staging)
            shutil.copytree(source, staging)
            if target.is_symlink() or target.is_file():
                target.unlink()
            elif target.is_dir():
                shutil.rmtree(target)
            staging.rename(target)
        for name in IN_PLACE:
            sync_in_place(ROOT / "supabase" / name, AGENT.parent / name)


def ensure_config() -> None:
    """Write the config file if it is missing or stale (through a temporary file, so a reader never sees half of it)."""
    AGENT.parent.mkdir(parents=True, exist_ok=True)
    wanted = generate(OWNER.read_text())
    if not AGENT.exists() or AGENT.read_text() != wanted:
        staging = AGENT.with_name(f".config.toml.{os.getpid()}")
        staging.write_text(wanted)
        staging.replace(AGENT)


def main(argv: list[str]) -> int:
    if "--sync" in argv or "--ensure" in argv:
        ensure_config()
        if "--sync" in argv:
            sync()
        return 0
    wanted = generate(OWNER.read_text())
    if "--check" in argv:
        if not AGENT.exists() or AGENT.read_text() != wanted:
            print("stacks/sme-ai-agent/supabase/config.toml is out of date: run python3 scripts/gen_agent_stack.py", file=sys.stderr)
            return 1
        return 0
    AGENT.parent.mkdir(parents=True, exist_ok=True)
    AGENT.write_text(wanted)
    print(f"wrote {AGENT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
