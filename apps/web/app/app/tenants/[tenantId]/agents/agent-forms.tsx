"use client";

import { useActionState } from "react";

import type { AgentActionState } from "./actions";
import { alertBox, btnMain, btnQuiet, hintInline, inlineForm, okBox, selectInline } from "@/components/v2/app/ui";
import { makeT, type Words } from "@/components/v2/app/words";

type Action = (prev: AgentActionState, formData: FormData) => Promise<AgentActionState>;

function Result({ state }: { state: AgentActionState }) {
  if (state?.error)
    return (
      <p role="alert" className={alertBox}>
        {state.error}
      </p>
    );
  if (state?.ok && state.message)
    return (
      <p role="status" className={okBox}>
        {state.message}
      </p>
    );
  return null;
}

/** The workspace switch. Rendered only for Owner/Admin (the API enforces the role regardless). */
export function AgentToggleForm({ action, enabled, words }: { action: Action; enabled: boolean; words?: Words; }) {
  const t = makeT(words);
  const [state, formAction, pending] = useActionState(action, undefined);
  return (
    <form action={formAction} className={inlineForm}>
      <input type="hidden" name="enabled" value={enabled ? "false" : "true"} />
      <button type="submit" className={btnMain} disabled={pending}>
        {pending ? t("ag.saving") : enabled ? t("ag.turn_agents_off") : t("ag.turn_agents_on")}
      </button>
      <Result state={state} />
    </form>
  );
}

export function StartRunForm({
  action,
  runId,
  companies, words,
}: {
  action: Action;
  /** Generated by the page for each render: one id per submit attempt. */
  runId: string;
  companies: { id: string; name: string }[]; words?: Words;
}) {
  const t = makeT(words);
  const [state, formAction, pending] = useActionState(action, undefined);
  return (
    <form action={formAction} className={inlineForm}>
      <input type="hidden" name="run_id" value={runId} />
      <label htmlFor="agent-company" className={hintInline}>
        {t("ag.company")}
      </label>{" "}
      <select id="agent-company" name="company_id" required disabled={pending} className={selectInline}>
        {companies.map((c) => (
          <option key={c.id} value={c.id}>
            {c.name}
          </option>
        ))}
      </select>{" "}
      <button type="submit" className={btnMain} disabled={pending || companies.length === 0}>
        {pending ? t("ag.starting") : t("ag.start_selftest_run")}
      </button>
      <Result state={state} />
    </form>
  );
}

