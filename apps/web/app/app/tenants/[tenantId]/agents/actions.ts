import { serverT } from "@/i18n/server-t";
import { makeT, type Say } from "@/components/v2/app/words";

export type AgentActionState = { ok?: boolean; error?: string; message?: string } | undefined;

function field(formData: FormData, name: string): string {
  const value = formData.get(name);
  return typeof value === "string" ? value.trim() : "";
}

/** Short, generic messages only: a raw API body or a submitted value is never shown. */
function explain(error: unknown, whatFor: string, t: Say = makeT()): string {
  if (error instanceof ApiAuthError) redirect("/login");
  if (error instanceof ApiRequestError) {
    if (error.status === 403) return t(`ag.role_cannot.${whatFor}`);
    if (error.status === 404) return t("ag.this_workspace_or_record_is_not");
    if (error.status === 409 && error.code === "agents_disabled")
      return t("ag.agents_are_not_enabled_for_this");
    if (error.status === 409 && error.code === "token_expiring")
      return t("ag.your_session_is_about_to_expire");
    if (error.status === 409 && error.code === "lead_has_no_company")
      return t("ag.that_lead_has_no_company_yet");
    if (error.status === 409 && error.code === "company_has_no_website")
      return t("ag.that_company_has_no_website_so");
    if (error.status === 409 && error.code === "archived")
      return t("ag.that_record_is_archived_so_it");
    if (error.status === 409)
      return t("ag.this_form_is_out_of_date");
    if (error.status === 429 && error.code === "ai_paused_until")
      return t("ag.ai_help_is_paused_because_this");
    if (error.status === 429) return t("ag.too_many_agent_runs_right_now");
    if (error.status === 503)
      return t("ag.agents_are_not_available_right_now");
  }
  return t(`ag.could_not.${whatFor}`);
}

/** The workspace switch (Owner/Admin; the API enforces it). Off by default. */
export async function toggleAgentsAction(
  tenantId: string,
  _prev: AgentActionState,
  formData: FormData,
): Promise<AgentActionState> {
  const t = await serverT(["ag."]);
  const user = await requireUser();
  if (!isCanonicalUuid(tenantId)) return { ok: false, error: t("ag.this_workspace_is_not_available") };
  const wanted = field(formData, "enabled");
  if (wanted !== "true" && wanted !== "false") return { ok: false, error: t("ag.choose_on_or_off") };
  try {
    await setAgentsEnabled(user.accessToken, tenantId, wanted === "true");
  } catch (error) {
    return { ok: false, error: explain(error, "change_this_setting", t) };
  }
  revalidatePath(`/app/tenants/${tenantId}/agents`);
  return { ok: true, message: wanted === "true" ? t("ag.agents_are_on_for_this_workspace") : t("ag.agents_are_off_for_this_workspace") };
}

/** Start one selftest run on a company. The run id is generated by the page, once per render (a retry re-sends it). */
export async function startRunAction(
  tenantId: string,
  _prev: AgentActionState,
  formData: FormData,
): Promise<AgentActionState> {
  const t = await serverT(["ag."]);
  const user = await requireUser();
  if (!isCanonicalUuid(tenantId)) return { ok: false, error: t("ag.this_workspace_is_not_available") };
  const runId = field(formData, "run_id");
  if (!isCanonicalUuid(runId)) return { ok: false, error: t("ag.this_form_is_out_of_date") };
  const companyId = field(formData, "company_id");
  if (!isCanonicalUuid(companyId)) return { ok: false, error: t("ag.choose_a_company") };
  try {
    await startSelftestRun(user.accessToken, tenantId, { id: runId, companyId });
  } catch (error) {
    return { ok: false, error: explain(error, "start_a_run", t) };
  }
  revalidatePath(`/app/tenants/${tenantId}/agents`);
  return { ok: true, message: t("ag.run_started_its_suggestions_will_appear") };
}

