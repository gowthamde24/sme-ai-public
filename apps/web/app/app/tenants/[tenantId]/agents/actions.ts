export async function cancelRunAction(
  tenantId: string,
  runId: string,
): Promise<AgentActionState> {
  const t = await serverT(["ag."]);
  const user = await requireUser();
  if (!isCanonicalUuid(tenantId) || !isCanonicalUuid(runId))
    return { ok: false, error: t("ag.this_run_is_not_available") };
  try {
    await cancelRun(user.accessToken, tenantId, runId);
  } catch (error) {
    return { ok: false, error: explain(error, "cancel_this_run", t) };
  }
  revalidatePath(`/app/tenants/${tenantId}/agents`);
  return { ok: true, message: t("ag.cancelled") };
}
