"use client";

import { useActionState, useState } from "react";

import type { ErasureResultOut } from "@/lib/api/erasure";

import type { PrivacyActionState } from "./actions";
import { alertBox, btnMain, btnQuiet, detailsBox, fieldInput, fieldLabel, legendText, okBox } from "@/components/v2/app/ui";
import { Rich } from "@/components/v2/app/rich";
import { makeT, type Words } from "@/components/v2/app/words";

type Action = (
  prev: PrivacyActionState,
  formData: FormData,
) => Promise<PrivacyActionState>;
/** A preview and a cancel need neither the previous state nor the form. */
type BareAction = () => Promise<PrivacyActionState>;

function Result({ state, words }: { state: PrivacyActionState; words?: Words; }) {
  if (state?.error)
    return (
      <p role="alert" className={alertBox}>
        {state.error}
      </p>
    );
  if (state?.ok && state.message)
    return (
      <div role="status" className={okBox}>
        <p>{state.message}</p>
        {state.result && <ResultView words={words} result={state.result} />}
      </div>
    );
  return null;
}

/** Counts per column and the rows to read by hand. Never a value: the API does not send one. */
export function ResultView({ result, words }: { result: ErasureResultOut; words?: Words; }) {
  const t = makeT(words);
  const entries = Object.entries(result.counts);
  return (
    <div>
      <p>
        <strong>{result.dry_run ? t("prv.would_change") : t("prv.changed")}:</strong>{" "}
        {entries.length === 0
          ? t("prv.nothing")
          : entries.map(([column, n]) => `${column} (${n})`).join(", ")}
      </p>
      {result.review.length > 0 && (
        <details className={detailsBox}>
          <summary>
            {result.review.length === 1 ? t("prv.review_one") : t("prv.review_many", { n: result.review.length })}
            {result.review_truncated ? " " + t("prv.the_list_is_cut_off") : ""}
          </summary>
          <p>
            {t("prv.these_rows_mention_the_name_inside")}
          </p>
          <ul>
            {result.review.map((item) => (
              <li key={`${item.table}.${item.column}.${item.id}`}>
                {t("prv.review_row", { table: item.table, column: item.column, id: item.id })}
              </li>
            ))}
          </ul>
        </details>
      )}
      {!result.dry_run && result.exports_logged > 0 && (
        <p>
          {result.exports_logged === 1 ? t("prv.exports_one") : t("prv.exports_many", { n: result.exports_logged })}
        </p>
      )}
      <p>{result.note}</p>
    </div>
  );
}

export function NewRequestForm({
  action,
  requestId,
  contacts,
  companies, words,
}: {
  action: Action;
  /** Generated by the page for each render: one id per submit attempt. */
  requestId: string;
  contacts: { id: string; name: string }[];
  companies: { id: string; name: string }[]; words?: Words;
}) {
  const t = makeT(words);
  const [state, formAction, pending] = useActionState(action, undefined);
  const [scope, setScope] = useState("contact");
  return (
    <form action={formAction}>
      <input type="hidden" name="request_id" value={requestId} />
      <fieldset>
        <legend className={legendText}>{t("prv.what_should_be_erased")}</legend>
        {[
          ["contact", t("prv.scope_contact")],
          ["company", t("prv.scope_company")],
          ["tenant", t("prv.scope_tenant")],
        ].map(([value, label]) => (
          <p key={value}>
            <label>
              <input
                type="radio"
                name="scope"
                value={value}
                checked={scope === value}
                onChange={() => setScope(value)}
                disabled={pending}
              />{" "}
              {label}
            </label>
          </p>
        ))}
      </fieldset>
      {scope === "contact" && (
        <p>
          <label htmlFor="erase-contact" className={fieldLabel}>
        {t("prv.contact")}
      </label>{" "}
          <select
            id="erase-contact"
            name="contact_id"
            required
            disabled={pending} className={fieldInput}>
            {contacts.map((c) => (
              <option key={c.id} value={c.id}>
                {c.name}
              </option>
            ))}
          </select>
        </p>
      )}
      {scope === "company" && (
        <p>
          <label htmlFor="erase-company" className={fieldLabel}>
        {t("prv.company")}
      </label>{" "}
          <select
            id="erase-company"
            name="company_id"
            required
            disabled={pending} className={fieldInput}>
            {companies.map((c) => (
              <option key={c.id} value={c.id}>
                {c.name}
              </option>
            ))}
          </select>
        </p>
      )}
      <button type="submit" className={btnMain} disabled={pending}>
        {pending ? t("prv.requesting") : t("prv.request_erasure")}
      </button>
      <Result words={words} state={state} />
    </form>
  );
}

/** Owner only. Shows what a run would change, and changes nothing. */
export function PreviewForm({ action, words }: { action: BareAction; words?: Words; }) {
  const t = makeT(words);
  const [state, formAction, pending] = useActionState(action, undefined);
  return (
    <form action={formAction}>
      <button type="submit" className={btnQuiet} disabled={pending}>
        {pending ? t("prv.checking") : t("prv.preview")}
      </button>
      <Result words={words} state={state} />
    </form>
  );
}

/**
 * Owner only. Irreversible: the Owner types the words shown (ERASE plus the subject's name, or the workspace slug). The button stays
 * disabled until they match; the server checks the words again against what the API says, so this is only a convenience.
 */
export function ExecuteForm({ action, phrase, words }: { action: Action; phrase: string; words?: Words; }) {
  const t = makeT(words);
  const [state, formAction, pending] = useActionState(action, undefined);
  const [typed, setTyped] = useState("");
  const matches = typed.replace(/\s+/g, " ").trim() === phrase;
  return (
    <form action={formAction}>
      <label>
        <Rich t={t} k="prv.confirm_type" with={{ phrase: <strong>{phrase}</strong> }} />
        <input
          type="text"
          name="confirm_text"
          value={typed}
          onChange={(event) => setTyped(event.target.value)}
          autoComplete="off"
          autoCapitalize="off"
          spellCheck={false}
          disabled={pending} className={fieldInput} />
      </label>{" "}
      <button type="submit" className={btnMain} disabled={pending || !matches}>
        {pending ? t("prv.erasing") : t("prv.erase_now")}
      </button>
      <Result words={words} state={state} />
    </form>
  );
}

export function CancelForm({ action, words }: { action: BareAction; words?: Words; }) {
  const t = makeT(words);
  const [state, formAction, pending] = useActionState(action, undefined);
  return (
    <form action={formAction}>
      <button type="submit" className={btnQuiet} disabled={pending}>
        {pending ? t("prv.cancelling") : t("prv.cancel_request")}
      </button>
      <Result words={words} state={state} />
    </form>
  );
}
