"""Generate packages/contracts/packs.schema.json and packs.ts from the pack, custom-field, example-data, sign-up-provider and second-factor models (job CK).

Same scheme as the other contracts (`make contracts`; a test fails if either file is stale). The TypeScript here also types a string-keyed object (`Record<string, T>`), which the older generators leave as unknown."""

from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from app.customfields import models as cf
from app.packs import models as m

HEADER = (
    "// GENERATED by `make contracts` from services/ai-api/app/packs/models.py and app/customfields/models.py. Do not edit.\n"
    "// A pack is DATA (packages/packs/<id>/pack.json): code reads module flags and never a pack id.\n"
)

RESPONSES: list[type[BaseModel]] = [
    m.PackListOut,
    m.WorkspacePackOut,
    m.WorkspaceModulesOut,
    m.ExampleDataStatusOut,
    m.ExampleDataRemoveOut,
    m.AuthProvidersOut,
    m.AccountSecurityOut,
    cf.CustomFieldListOut,
    cf.CustomFieldDefOut,
    cf.CustomValuesOut,
]
REQUESTS: list[type[BaseModel]] = [cf.CustomFieldCreateIn, cf.CustomFieldPatchIn, cf.CustomValuesIn]


def build_schema() -> dict[str, Any]:
    _, defs = models_json_schema(
        [(model, "serialization") for model in RESPONSES] + [(model, "validation") for model in REQUESTS],
        ref_template="#/$defs/{model}",
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "packs.schema.json",
        "title": "Packs, modules, custom fields, example data and sign-up contracts (job CK)",
        "description": (
            "Generated from services/ai-api/app/packs/models.py and app/customfields/models.py by `make contracts`. "
            "GET /v1/packs and GET /v1/auth/providers need no sign-in. Requests forbid unknown properties: a tenant, a pack id or a personal-data class can never be sent."
        ),
        "$defs": dict(sorted(defs.get("$defs", {}).items())),
    }


def schema_text() -> str:
    return json.dumps(build_schema(), indent=2, sort_keys=False) + "\n"


def _ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[-1].replace("_", "")
    if "anyOf" in node:
        return " | ".join(sorted({_ts_type(option) for option in node["anyOf"]}, key=lambda t: (t == "null", t)))
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    kind = node.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = _ts_type(node.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {_ts_type(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def ts_text() -> str:
    defs = build_schema()["$defs"]
    lines = [HEADER]
    for name, node in defs.items():
        ts_name = name.replace("_", "")
        if "enum" in node:
            lines.append(f"export type {ts_name} = {_ts_type(node)};\n")
            continue
        props = node.get("properties", {})
        required = set(node.get("required", []))
        body = []
        for prop, spec in props.items():
            optional = "" if prop in required else "?"
            body.append(f"  {prop}{optional}: {_ts_type(spec)};")
        lines.append(f"export interface {ts_name} {{\n" + "\n".join(body) + "\n}\n")
    return "\n".join(lines)
