"""Generate packages/contracts/campaigns.schema.json and campaigns.ts from the models of the reminder campaigns, the call list and the shared ledger's new endpoints (job CP, ADR 0086).

Same scheme as the other contracts (`make contracts`; a test fails if either file is stale). The contract is committed EARLY on purpose: the screens (campaigns, the call list, the results, the fee ledger and
receipts) are built against it by the web lane."""

from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from app.campaigns import models as c
from app.dues import models as u
from app.packs.contracts import _ts_type

HEADER = (
    "// GENERATED by `make contracts` from services/ai-api/app/{campaigns,dues}/models.py. Do not edit.\n"
    "// Money is integer paise and comes only from a list, a ledger entry or an import a person made. A campaign is approved ONCE by the Owner, for the samples they saw (`samples_sha256`).\n"
)

RESPONSES: list[type[BaseModel]] = [
    c.CampaignOut,
    c.CampaignDetailOut,
    c.CampaignSavedOut,
    c.CampaignListOut,
    c.RecipientsAddedOut,
    c.RemovedOut,
    c.RecipientOut,
    c.PreviewOut,
    c.ApprovedOut,
    c.ResultsOut,
    c.CallItemOut,
    c.CallListOut,
    c.OutcomeRecordedOut,
    u.EntryRecordedOut,
    u.EntryVoidedOut,
    u.EntriesOut,
    u.ChargesImportOut,
    u.ReceiptOut,
]
REQUESTS: list[type[BaseModel]] = [
    c.CampaignIn,
    c.RecipientsIn,
    c.LedgerFilterIn,
    c.ApproveIn,
    c.OutcomeIn,
    u.EntryIn,
    u.ChargesImportIn,
]


def build_schema() -> dict[str, Any]:
    _, defs = models_json_schema(
        [(model, "serialization") for model in RESPONSES] + [(model, "validation") for model in REQUESTS],
        ref_template="#/$defs/{model}",
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "campaigns.schema.json",
        "title": "Reminder campaigns, the call list and the shared ledger (job CP)",
        "description": (
            "Generated from services/ai-api/app/{campaigns,dues}/models.py by `make contracts`. Requests forbid unknown properties: a status, an approver, a sender, a rendered text or an amount a model made "
            "can never be sent."
        ),
        "$defs": dict(sorted(defs.get("$defs", {}).items())),
    }


def schema_text() -> str:
    return json.dumps(build_schema(), indent=2, sort_keys=False) + "\n"


def ts_text() -> str:
    defs = build_schema()["$defs"]
    lines = [HEADER]
    for name, node in defs.items():
        ts_name = name.replace("_", "")
        if "enum" in node:
            lines.append(f"export type {ts_name} = {_ts_type(node)};\n")
            continue
        props = node.get("properties", {})
        required = set(node.get("required", []))
        body = []
        for prop, spec in props.items():
            optional = "" if prop in required else "?"
            body.append(f"  {prop}{optional}: {_ts_type(spec)};")
        lines.append(f"export interface {ts_name} {{\n" + "\n".join(body) + "\n}\n")
    return "\n".join(lines)
