"""Generate packages/contracts/voice_notes.schema.json and voice_notes.ts from the models of the voice notes API (job CV, ADR 0088). Same scheme as the other contracts (`make contracts`; a test fails if either
file is stale). The contract is committed early for the web lane: the voice switch, the voice for each language, the spoken-disclosure line and the fair-use meter are built against it."""

from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from app.packs.contracts import _ts_type
from app.voice_notes import models as m

HEADER = (
    "// GENERATED by `make contracts` from services/ai-api/app/voice_notes/models.py. Do not edit.\n"
    "// Audio is counted in seconds, never in rupees or tokens. A voice note is the approved words, preceded by a spoken AI disclosure; it is made at send time and never stored.\n"
)
RESPONSES: list[type[BaseModel]] = [
    m.VoiceSettingsOut,
    m.VoicesOut,
    m.VoiceOut,
    m.DisclosureOut,
    m.UsageOut,
    m.CampaignVoiceOut,
    m.PreviewOut,
]
REQUESTS: list[type[BaseModel]] = [m.VoiceSettingsIn, m.VoiceChoiceIn, m.CampaignVoiceIn, m.PreviewIn]


def build_schema() -> dict[str, Any]:
    _, defs = models_json_schema(
        [(model, "serialization") for model in RESPONSES] + [(model, "validation") for model in REQUESTS], ref_template="#/$defs/{model}"
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "voice_notes.schema.json",
        "title": "Voice notes: settings, voices, the spoken disclosure, the fair-use meter (job CV)",
        "description": "Generated from services/ai-api/app/voice_notes/models.py by `make contracts`.",
        "$defs": dict(sorted(defs.get("$defs", {}).items())),
    }


def schema_text() -> str:
    return json.dumps(build_schema(), indent=2, sort_keys=False) + "\n"


def ts_text() -> str:
    defs = build_schema()["$defs"]
    lines = [HEADER]
    for name, node in defs.items():
        ts_name = name.replace("_", "")
        if "enum" in node:
            lines.append(f"export type {ts_name} = {_ts_type(node)};\n")
            continue
        props = node.get("properties", {})
        required = set(node.get("required", []))
        body = []
        for prop, spec in props.items():
            optional = "" if prop in required else "?"
            body.append(f"  {prop}{optional}: {_ts_type(spec)};")
        lines.append(f"export interface {ts_name} {{\n" + "\n".join(body) + "\n}\n")
    return "\n".join(lines)
