"""Generate packages/contracts/education.schema.json and education.ts from the models of the education pack (job CR, ADR 0087).

Same scheme as the other contracts (`make contracts`; a test fails if either file is stale). The contract is committed EARLY on purpose: the education screens (students and guardians import, fee plans, ledger,
receipts, the collection dashboard, the admissions board, announcements) are built against it by the web lane. Children's data is the minimum of ADR 0084 part 5: a response that carries a child's label is
only ever sent to a signed-in Owner, Admin or Sales member."""

from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from app.education import models as m
from app.packs.contracts import _ts_type

HEADER = (
    "// GENERATED by `make contracts` from services/ai-api/app/education/models.py. Do not edit.\n"
    "// Money is integer paise and comes only from a fee plan or an entry a person made. A student is the minimum: a first name or initials, a placement, an optional admission number and the adult we write to.\n"
)

RESPONSES: list[type[BaseModel]] = [
    m.ProfileOut,
    m.ProgrammesOut,
    m.ProgrammeSavedOut,
    m.GroupSavedOut,
    m.StudentOut,
    m.StudentSavedOut,
    m.StudentsOut,
    m.ErasedOut,
    m.ImportRowOut,
    m.AdmissionOut,
    m.AdmissionCreatedOut,
    m.AdmissionDetailOut,
    m.AdmissionsOut,
    m.StageChangedOut,
    m.AdmittedOut,
    m.FeePlanOut,
    m.FeePlanDetailOut,
    m.FeePlansOut,
    m.AssignedOut,
    m.AssignmentVoidedOut,
    m.PaymentRecordedOut,
    m.ConcessionRecordedOut,
    m.AdjustmentRecordedOut,
    m.FeeStatementOut,
    m.FeeEntriesOut,
    m.FeeReceiptOut,
    m.GuardianFeesOut,
    m.LateFeesPreviewOut,
    m.LateFeesPostedOut,
    m.PendingListOut,
    m.AudienceAddedOut,
    m.ReportOut,
]
REQUESTS: list[type[BaseModel]] = [
    m.ProfileIn,
    m.ProgrammeIn,
    m.GroupIn,
    m.StudentIn,
    m.StatusIn,
    m.AdmissionIn,
    m.StageIn,
    m.AdmitIn,
    m.FeePlanIn,
    m.AssignIn,
    m.PaymentIn,
    m.ConcessionIn,
    m.AdjustmentIn,
    m.AudienceIn,
]


def build_schema() -> dict[str, Any]:
    _, defs = models_json_schema(
        [(model, "serialization") for model in RESPONSES] + [(model, "validation") for model in REQUESTS],
        ref_template="#/$defs/{model}",
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "education.schema.json",
        "title": "The education pack: programmes, students, admissions, fees (job CR)",
        "description": (
            "Generated from services/ai-api/app/education/models.py by `make contracts`. Requests forbid unknown properties: a date of birth, a photograph, an address, an identity number, a note or an amount a model "
            "made can never be sent."
        ),
        "$defs": dict(sorted(defs.get("$defs", {}).items())),
    }


def schema_text() -> str:
    return json.dumps(build_schema(), indent=2, sort_keys=False) + "\n"


def ts_text() -> str:
    defs = build_schema()["$defs"]
    lines = [HEADER]
    for name, node in defs.items():
        ts_name = name.replace("_", "")
        if "enum" in node:
            lines.append(f"export type {ts_name} = {_ts_type(node)};\n")
            continue
        props = node.get("properties", {})
        required = set(node.get("required", []))
        body = []
        for prop, spec in props.items():
            optional = "" if prop in required else "?"
            body.append(f"  {prop}{optional}: {_ts_type(spec)};")
        lines.append(f"export interface {ts_name} {{\n" + "\n".join(body) + "\n}\n")
    return "\n".join(lines)
