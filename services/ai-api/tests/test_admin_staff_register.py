def test_nothing_secret_is_written_anywhere_in_the_script() -> None:
    text = (SCRIPTS / "admin_staff_register.py").read_text()
    assert not re.search(r"(?<![A-Za-z_.])open\(", text) and "write_text" not in text and "environ" not in text   # no file, no environment variable carries the password or the factor secret
    assert text.count("getpass.getpass") >= 3


def svg_of(grid: list[list[bool]], step: int = 3, offset: int = 12) -> str:
    """The Auth service's QR shape: one square per module, black or white (what `totp.qr_code` holds)."""
    rects = "\n".join(f'<rect x="{offset + c * step}" y="{offset + r * step}" width="{step}" height="{step}" style="fill:{"black" if v else "white"};stroke:none" />' for r, row in enumerate(grid) for c, v in enumerate(row))
    side = offset * 2 + len(grid) * step
    return f'<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg width="{side}" height="{side}"\n     xmlns="http://www.w3.org/2000/svg">\n{rects}\n</svg>'


def fake_code(n: int = 21) -> list[list[bool]]:
    grid = [[(r * 7 + c * 3) % 5 < 2 for c in range(n)] for r in range(n)]   # filler modules
    for top, left in ((0, 0), (0, n - 7), (n - 7, 0)):   # the three finder squares
        for i in range(7):
            for j in range(7):
                grid[top + i][left + j] = max(abs(i - 3), abs(j - 3)) != 2
    return grid



def test_the_qr_code_is_parsed_checked_and_drawn_in_the_terminal_without_a_file() -> None:
    m = load()
    grid = fake_code()
    assert m.parse_qr_svg(svg_of(grid)) == grid and m.has_finder_patterns(grid)
    assert m.parse_qr_svg("data:image/svg+xml;utf-8," + svg_of(grid).replace("<", "%3C").replace(">", "%3E").replace(" ", "%20").replace('"', "%22")) == grid
    broken = [row[:] for row in grid]
    broken[3][3] = not broken[3][3]   # damage a finder square
    assert not m.has_finder_patterns(broken)
    for bad in ("", "<svg></svg>", svg_of([[True] * 20 for _ in range(20)])):
        with pytest.raises(m.StaffError):
            m.parse_qr_svg(bad)
    drawn = m.render_qr(grid).split("\n")
    assert len(drawn) == (21 + 2 * m.QUIET + 1) // 2 and "\u2580" in drawn[0]
    # drawing it back gives the same modules (explicit black and white, so it scans on a dark or a light theme)
    rows: list[list[bool]] = []
    for line in drawn:
        cells = re.findall(r"38;5;(\d+);48;5;(\d+)m", line)
        rows.append([int(top) == 16 for top, _ in cells])
        rows.append([int(bottom) == 16 for _, bottom in cells])
    q = m.QUIET
    assert [r[q:q + 21] for r in rows[q:q + 21]] == grid
    source = (SCRIPTS / "admin_staff_register.py").read_text()
    assert not re.search(r"(?<![A-Za-z_.])open\(|write_text|tempfile|NamedTemporary", source)   # no image file


def test_the_setup_key_is_never_printed_and_show_secret_uses_the_clipboard(monkeypatch: pytest.MonkeyPatch) -> None:
    m = load()
    lines = (SCRIPTS / "admin_staff_register.py").read_text().splitlines()
    assert not [ln for ln in lines if "print(" in ln and ('["secret"]' in ln or '["uri"]' in ln or "otpauth" in ln)]   # nothing prints the key
    use = [i for i, ln in enumerate(lines) if 'copy_to_clipboard(str(enrol["totp"]["secret"]))' in ln]
    assert len(use) == 1 and "if args.show_secret" in lines[use[0] - 1]   # only behind the flag
    sent: list[str] = []

    def fake_run(argv: Any, input: str | None = None, **kw: Any) -> None:
        sent.append(str(input))

    monkeypatch.setattr(m.subprocess, "run", fake_run)
    m.copy_to_clipboard("JBSWY3DPEHPK3PXP")
    m.copy_to_clipboard("")
    assert sent == ["JBSWY3DPEHPK3PXP", ""]   # copied, then cleared

    def boom(*a: Any, **kw: Any) -> None:
        raise FileNotFoundError("pbcopy")

    monkeypatch.setattr(m.subprocess, "run", boom)
    with pytest.raises(m.StaffError):
        m.copy_to_clipboard("x")   # no clipboard tool: it stops instead of showing the key
