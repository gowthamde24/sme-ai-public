-- ONE dedicated system account for the billing webhook (owner approved 13 Nov 2026): only that account (and the business's Owner) may settle an order, so a scheduler or channel account can no longer mint money.
--   * `pricing.webhook_principals` holds the account; `app.operator_register_billing_webhook(email)` registers it (operator only; the account belongs to no workspace and is no other kind of system account).
--   * public.pricing_order_settle: the business's Owner (after the checked payment) OR the billing webhook account. Scheduler and channel accounts are refused.
--   * public.pricing_topup_credit (credits the wallet from a payment; nothing in the app calls it today): the billing webhook account only.
--   * public.pricing_provider_event (renewals, halts, cancels): the billing webhook account, and the scheduler / channel accounts as before (they do not move money).
-- The account's password is generated by scripts/billing_webhook_account.py straight into Secret Manager (never printed, never in a file); the API signs in with it to apply the signed Razorpay events.

create table pricing.webhook_principals (
  user_id    uuid primary key references auth.users (id) on delete restrict,
  created_at timestamptz not null default now()
);
alter table pricing.webhook_principals enable row level security;
alter table pricing.webhook_principals force row level security;
revoke all on pricing.webhook_principals from public, anon, authenticated, service_role;

create function app.is_billing_webhook() returns boolean language sql stable security definer set search_path = '' as
$$ select auth.uid() is not null and exists (select 1 from pricing.webhook_principals p where p.user_id = auth.uid()) $$;
revoke all on function app.is_billing_webhook() from public, anon, authenticated, service_role;

create function app.operator_register_billing_webhook(p_email text) returns uuid language plpgsql set search_path = '' as
$$
declare v_id uuid;
begin
  if auth.uid() is not null then
    raise exception 'operator only' using errcode = '42501';
  end if;
  select u.id into v_id from auth.users u where lower(u.email) = lower(btrim(coalesce(p_email, '')));
  if v_id is null then
    raise exception 'no such account' using errcode = '23503';
  end if;
  -- one kind of account per person: not a shop member, not staff, not the scheduler, not a channel agent
  if exists (select 1 from public.memberships m where m.user_id = v_id) or exists (select 1 from admin.staff s where s.user_id = v_id)
     or exists (select 1 from scheduler.principals sp where sp.user_id = v_id) or exists (select 1 from integrations.channel_principals cp where cp.user_id = v_id) then
    raise exception 'the billing webhook account is no other kind of account' using errcode = '42501';
  end if;
  insert into pricing.webhook_principals (user_id) values (v_id) on conflict do nothing;
  return v_id;
end $$;
revoke all on function app.operator_register_billing_webhook(text) from public, anon, authenticated, service_role;

create function app.operator_remove_billing_webhook(p_email text) returns void language plpgsql set search_path = '' as
$$
begin
  if auth.uid() is not null then
    raise exception 'operator only' using errcode = '42501';
  end if;
  delete from pricing.webhook_principals p where p.user_id = (select u.id from auth.users u where lower(u.email) = lower(btrim(coalesce(p_email, ''))));
end $$;
revoke all on function app.operator_remove_billing_webhook(text) from public, anon, authenticated, service_role;

create function pricing.webhook_only() returns void language plpgsql set search_path = '' as
$$ begin if auth.uid() is null or not app.is_billing_webhook() then raise exception 'not allowed' using errcode = '42501'; end if; end $$;
create function pricing.system_or_webhook() returns void language plpgsql set search_path = '' as
$$ begin if auth.uid() is null or not (app.is_scheduler() or app.is_channel_agent() or app.is_billing_webhook()) then raise exception 'not allowed' using errcode = '42501'; end if; end $$;
revoke all on function pricing.webhook_only(), pricing.system_or_webhook() from public, anon, authenticated, service_role;

-- the three functions again, with only their access check changed
create or replace function public.pricing_order_settle(p_tenant_id uuid, p_order_id text, p_payment_ref text) returns jsonb language plpgsql security definer set search_path = '' as
$$
declare
  o     pricing.orders;
  v_sub pricing.subscriptions;
  v_start timestamptz;
begin
  if auth.uid() is null or p_tenant_id is null or not (app.has_tenant_role(p_tenant_id, array['owner']::public.app_role[]) or app.is_billing_webhook()) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if p_order_id is null or p_payment_ref is null or p_payment_ref !~ '^[A-Za-z0-9_.:-]{3,100}$' then
    raise exception 'invalid input' using errcode = '22023';
  end if;
  select * into o from pricing.orders x where x.order_id = p_order_id and x.tenant_id = p_tenant_id for update;
  if not found then
    raise exception 'not found' using errcode = '23503';
  end if;
  if o.status = 'paid' then
    return jsonb_build_object('settled', false, 'replayed', true, 'purpose', o.purpose);
  end if;
  update pricing.orders set status = 'paid', payment_ref = p_payment_ref, paid_at = now() where order_id = o.order_id;
  if o.purpose = 'topup' then
    perform pricing.credit(o.tenant_id, 'topup', p_payment_ref, o.base_paise);
    perform pricing.invoice(o.tenant_id, 'topup', p_payment_ref, o.base_paise);
  elsif o.purpose = 'payg_fee' then
    select * into v_sub from pricing.subscriptions s where s.tenant_id = o.tenant_id for update;
    v_start := case when v_sub.tenant_id is not null and v_sub.period_end > now() then v_sub.period_end else now() end;
    insert into pricing.subscriptions as s (tenant_id, plan_id, interval, status, provider, provider_ref, period_start, period_end, price_locked_until)
    values (o.tenant_id, 'payg', 'monthly', 'active', 'razorpay', null, v_start, pricing.period_end(v_start, 'monthly'), now() + make_interval(months => (select x.launch_lock_months from pricing.settings x)))
    on conflict (tenant_id) do update set plan_id = 'payg', interval = 'monthly', status = 'active', period_start = excluded.period_start, period_end = excluded.period_end, updated_at = now();
    perform pricing.invoice(o.tenant_id, 'payg_fee', p_payment_ref, o.base_paise);
  else
    perform pricing.apply_change(o.tenant_id, o.plan_id, o.interval, p_payment_ref);
  end if;
  return jsonb_build_object('settled', true, 'replayed', false, 'purpose', o.purpose);
end $$;

create or replace function public.pricing_provider_event(p_tenant_id uuid, p_event_id text, p_kind text, p_amount_paise bigint) returns jsonb language plpgsql security definer set search_path = '' as
$$
declare
  v_sub pricing.subscriptions;
  v_n   integer;
  v_start timestamptz;
begin
  perform pricing.system_or_webhook();
  if p_tenant_id is null or p_event_id is null or p_event_id !~ '^[A-Za-z0-9_:.-]{3,120}$' or p_kind not in ('charge_succeeded', 'charge_failed', 'halted', 'cancelled', 'payg_fee') then
    raise exception 'invalid input' using errcode = '22023';
  end if;
  insert into pricing.events (tenant_id, event_id, kind) values (p_tenant_id, p_event_id, p_kind) on conflict do nothing;
  get diagnostics v_n = row_count;
  if v_n = 0 then
    return jsonb_build_object('applied', false, 'replayed', true);
  end if;
  select * into v_sub from pricing.subscriptions s where s.tenant_id = p_tenant_id for update;
  if v_sub.tenant_id is null then
    return jsonb_build_object('applied', false, 'replayed', false, 'reason', 'no_subscription');
  end if;
  if p_kind in ('charge_succeeded', 'payg_fee') then
    v_start := case when v_sub.period_end > now() then v_sub.period_end else now() end;
    update pricing.subscriptions set status = 'active', period_start = v_start, period_end = pricing.period_end(v_start, v_sub.interval), updated_at = now() where tenant_id = p_tenant_id;
    perform pricing.invoice(p_tenant_id, case when p_kind = 'payg_fee' then 'payg_fee' else 'subscription' end, p_event_id,
                            coalesce(p_amount_paise, pricing.price_of(v_sub.plan_id, v_sub.interval)));
  elsif p_kind = 'halted' or p_kind = 'charge_failed' then
    update pricing.subscriptions set status = 'past_due', updated_at = now() where tenant_id = p_tenant_id;
  elsif p_kind = 'cancelled' then
    update pricing.subscriptions set status = 'cancelled', updated_at = now() where tenant_id = p_tenant_id;
  end if;
  return jsonb_build_object('applied', true, 'replayed', false);
end $$;

create or replace function public.pricing_topup_credit(p_tenant_id uuid, p_payment_ref text, p_amount_paise bigint) returns jsonb language plpgsql security definer set search_path = '' as
$$
declare
  v_new boolean;
begin
  perform pricing.webhook_only();
  if p_tenant_id is null or p_payment_ref is null or p_payment_ref !~ '^[A-Za-z0-9_.:-]{3,100}$' or p_amount_paise is null or p_amount_paise not between 100 and 100000000 then
    raise exception 'invalid input' using errcode = '22023';
  end if;
  v_new := pricing.credit(p_tenant_id, 'topup', p_payment_ref, p_amount_paise);
  return jsonb_build_object('credited', v_new, 'balance_paise', pricing.balance_of(p_tenant_id), 'invoice', pricing.invoice(p_tenant_id, 'topup', p_payment_ref, p_amount_paise));
end $$;
