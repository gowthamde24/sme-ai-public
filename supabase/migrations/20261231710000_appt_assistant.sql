-- ---------------------------------------------------------------------------------------------------------------------------------
-- the free slots, offered to a customer
-- ---------------------------------------------------------------------------------------------------------------------------------
-- p_visit_id set = "move this visit" (it must be the customer's own, live and in the future)
create function public.appointment_offer_slots(p_tenant_id uuid, p_lead_id uuid, p_language text, p_limit integer default 3, p_days integer default 5, p_visit_id uuid default null) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now   timestamptz := app.visit_now();
  v_slots jsonb;
  v_list  jsonb;
  v_id    uuid := gen_random_uuid();
  v_lead  public.leads;
  v_visit public.store_visits;
begin
  if not app.is_scheduler() then
    perform app.visit_error('deny');
  end if;
  if p_tenant_id is null or p_lead_id is null or p_language is null or p_language not in ('en', 'te', 'hi', 'kn', 'ta', 'ml', 'mr') or p_limit is null or p_limit not between 1 and 5 or p_days is null or p_days not between 1 and 14 then
    perform app.visit_error('invalid');
  end if;
  if not app.appointment_assistant_may(p_tenant_id) then
    return jsonb_build_object('offer_id', null, 'offered', '[]'::jsonb, 'reason', 'off');
  end if;
  select * into v_lead from public.leads l where l.id = p_lead_id and l.tenant_id = p_tenant_id and l.archived_at is null;
  if not found then
    perform app.visit_error('reference');
  end if;
  if exists (select 1 from public.contacts c where c.id = v_lead.contact_id and c.tenant_id = p_tenant_id and c.erased_at is not null) then
    perform app.visit_error('stopped');
  end if;
  if p_visit_id is not null then
    select * into v_visit from public.store_visits v where v.id = p_visit_id and v.tenant_id = p_tenant_id and v.lead_id = p_lead_id and v.status in ('booked', 'confirmed') and v.starts_at > v_now;
    if not found then
      return jsonb_build_object('offer_id', null, 'offered', '[]'::jsonb, 'reason', 'no_visit');
    end if;
  end if;
  v_slots := public.visit_slots_for_call(p_tenant_id, p_days, p_limit);
  if jsonb_array_length(v_slots) = 0 then
    return jsonb_build_object('offer_id', null, 'offered', '[]'::jsonb, 'reason', 'no_free_slot');
  end if;
  select jsonb_agg(jsonb_build_object('n', o.n, 'date', o.x ->> 'date', 'start', o.x ->> 'start', 'starts_at', o.x -> 'starts_at') order by o.n) into v_list from jsonb_array_elements(v_slots) with ordinality o (x, n);
  update public.booking_offers set state = 'superseded' where tenant_id = p_tenant_id and lead_id = p_lead_id and state = 'open';
  insert into public.booking_offers (id, tenant_id, lead_id, for_visit, language, slots, expires_at) values (v_id, p_tenant_id, p_lead_id, p_visit_id, p_language, v_list, v_now + interval '30 minutes');
  return jsonb_build_object('offer_id', v_id, 'offered', v_list, 'reason', null);
end;
$$;
revoke all on function public.appointment_offer_slots(uuid, uuid, text, integer, integer, uuid) from public, anon;
grant execute on function public.appointment_offer_slots(uuid, uuid, text, integer, integer, uuid) to authenticated;

-- ---------------------------------------------------------------------------------------------------------------------------------
-- the customer's choice (1, 2, 3 ...) of the offer: a new booking, or the move of the visit the offer was for
-- ---------------------------------------------------------------------------------------------------------------------------------
create function public.appointment_book_choice(p_tenant_id uuid, p_lead_id uuid, p_choice integer, p_visit_id uuid, p_party_size integer default 1) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := auth.uid();
  v_now    timestamptz := app.visit_now();
  o        public.booking_offers;
  v_pick   jsonb;
  v_lead   public.leads;
  v_contact public.contacts;
  v_slot   record;
  m        public.store_visits;
  v_old    public.store_visits;
  v_sha    text;
  v_date   date;
  v_start  text;
begin
  if not app.is_scheduler() then
    perform app.visit_error('deny');
  end if;
  if p_tenant_id is null or p_lead_id is null or p_choice is null or p_choice not between 1 and 12 or p_visit_id is null or p_party_size is null or p_party_size not between 1 and 50 then
    perform app.visit_error('invalid');
  end if;
  if not app.appointment_assistant_may(p_tenant_id) then
    return jsonb_build_object('status', 'off');
  end if;
  -- a retry of the same booking
  select * into v_old from public.store_visits x where x.id = p_visit_id;
  if found then
    if v_old.tenant_id <> p_tenant_id or v_old.lead_id <> p_lead_id then
      perform app.visit_error('conflict');
    end if;
    return jsonb_build_object('status', 'booked', 'visit_id', v_old.id, 'starts_at', v_old.starts_at, 'staff_id', v_old.staff_id, 'replayed', true);
  end if;
  select * into o from public.booking_offers b where b.tenant_id = p_tenant_id and b.lead_id = p_lead_id and b.state = 'open' order by b.created_at desc limit 1 for update;
  if not found or o.expires_at <= v_now then
    return jsonb_build_object('status', 'no_offer');
  end if;
  select x into v_pick from jsonb_array_elements(o.slots) x where (x ->> 'n')::integer = p_choice;
  if v_pick is null then
    return jsonb_build_object('status', 'bad_choice');
  end if;
  v_date := (v_pick ->> 'date')::date;
  v_start := v_pick ->> 'start';
  select * into v_lead from public.leads l where l.id = p_lead_id and l.tenant_id = p_tenant_id;
  if v_lead.contact_id is not null then
    select * into v_contact from public.contacts c where c.id = v_lead.contact_id and c.tenant_id = p_tenant_id;
    if v_contact.erased_at is not null then
      perform app.visit_error('stopped');
    end if;
  end if;
  begin
    if o.for_visit is not null then
      -- MOVE the customer's own visit
      select * into m from public.store_visits x where x.id = o.for_visit and x.tenant_id = p_tenant_id and x.lead_id = p_lead_id and x.status in ('booked', 'confirmed') for update;
      if not found then
        update public.booking_offers set state = 'superseded' where id = o.id;
        return jsonb_build_object('status', 'no_visit');
      end if;
      select * into v_slot from app.visit_claim_slot(p_tenant_id, v_date, v_start, m.id, null, m.staff_id);
      update public.store_visits
         set visit_date = v_date, starts_at = v_slot.o_starts, ends_at = v_slot.o_ends, staff_id = v_slot.o_staff,
             buffer_minutes = coalesce((v_slot.o_set ->> 'buffer_minutes')::smallint, 0), status = 'booked', confirmed_at = null, language = o.language, updated_by = v_uid
       where id = m.id returning * into m;
    else
      select * into v_slot from app.visit_claim_slot(p_tenant_id, v_date, v_start, null, null);
      if exists (select 1 from public.store_visits x where x.tenant_id = p_tenant_id and x.lead_id = p_lead_id and x.starts_at = v_slot.o_starts and x.status in ('booked', 'confirmed', 'arrived')) then
        perform app.visit_error('state');
      end if;
      v_sha := encode(sha256(convert_to(concat_ws('|', p_lead_id, v_date, v_start, p_party_size, 'assistant', o.id), 'UTF8')), 'hex');
      insert into public.store_visits
        (id, tenant_id, lead_id, contact_id, company_id, visit_date, starts_at, ends_at, party_size, source, request_sha256, created_by, created_at, updated_by, staff_id, buffer_minutes, language)
      values
        (p_visit_id, p_tenant_id, p_lead_id, v_contact.id, v_lead.company_id, v_date, v_slot.o_starts, v_slot.o_ends, p_party_size, 'assistant', v_sha, v_uid, v_now, v_uid,
         v_slot.o_staff, coalesce((v_slot.o_set ->> 'buffer_minutes')::smallint, 0), o.language)
      returning * into m;
    end if;
  exception
    when exclusion_violation then
      return jsonb_build_object('status', 'taken');
    when sqlstate 'SM513' then
      return jsonb_build_object('status', 'taken');   -- somebody else got it first: the caller offers new times
  end;
  update public.booking_offers set state = 'used' where id = o.id;
  return jsonb_build_object('status', 'booked', 'visit_id', m.id, 'starts_at', m.starts_at, 'staff_id', m.staff_id, 'moved', o.for_visit is not null, 'replayed', false,
                            'staff_name', (select s.name from public.store_staff s where s.id = m.staff_id));
end;
$$;
revoke all on function public.appointment_book_choice(uuid, uuid, integer, uuid, integer) from public, anon;
grant execute on function public.appointment_book_choice(uuid, uuid, integer, uuid, integer) to authenticated;

