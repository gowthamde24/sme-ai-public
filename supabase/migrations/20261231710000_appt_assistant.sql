-- Appointment booking, slice 2 + 3 (docs/plans/appointment-booking.md): the ASSISTANT books for a customer (WhatsApp, phone) and the booking is CONFIRMED by message on its own.
--   * public.booking_offers: the free slots the assistant offered a customer ("reply 1, 2 or 3"), valid 30 minutes, one open offer per customer. A customer's choice is resolved against THIS list, never against words.
--   * public.appointment_offer_slots / appointment_book_choice / appointment_cancel_for_customer: the scheduler account (the worker that answers WhatsApp and the phone line) books, moves and cancels for
--     a customer. The same rules as the app (app.visit_claim_slot: hours, closed days, buffer, staff, capacity, Google busy time, one person cannot overlap themselves), only for a business that has
--     the visits module on AND lets its assistant book visits (assistant_settings.may_book_visits). A customer can only ever touch THEIR OWN visits (matched by the lead).
--   * scheduler_due_confirmations / scheduler_confirm_booking: a visit the assistant booked becomes `confirmed` and its WhatsApp confirmation is queued in the outbox (policy, consent, STOP, quiet hours
--     and the per-customer limit still decide whether it goes). A moved visit is confirmed again for its new time.
--   * store_visits.language (the language the customer spoke), store_visits.confirmed_for (the start time the confirmation was made for).
-- The reminders (the evening before, 2 hours before, never in quiet hours) already exist (job AW) and apply to confirmed visits, including these.

alter table public.store_visits add column language text check (language in ('en', 'te', 'hi', 'kn', 'ta', 'ml', 'mr'));
alter table public.store_visits add column confirmed_for timestamptz;
comment on column public.store_visits.language is 'SAFE: a closed word. CLEAN-EXEMPT: closed CHECK list';
comment on column public.store_visits.confirmed_for is 'SAFE: a time: the start the confirmation message was made for';

create table public.booking_offers (
  id         uuid primary key,
  tenant_id  uuid not null references public.tenants (id) on delete restrict,
  lead_id    uuid not null,
  for_visit  uuid,                       -- set when the customer asked to MOVE a visit (the offer is for that visit)
  language   text not null check (language in ('en', 'te', 'hi', 'kn', 'ta', 'ml', 'mr')),
  slots      jsonb not null check (jsonb_typeof(slots) = 'array' and jsonb_array_length(slots) between 1 and 12),
  state      text not null default 'open' check (state in ('open', 'used', 'superseded')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  unique (tenant_id, id),
  foreign key (tenant_id, lead_id) references public.leads (tenant_id, id),
  foreign key (tenant_id, for_visit) references public.store_visits (tenant_id, id)
);
comment on column public.booking_offers.language is 'SAFE: a closed word. CLEAN-EXEMPT: closed CHECK list';
comment on column public.booking_offers.state is 'SAFE: a closed word. CLEAN-EXEMPT: closed CHECK list';
comment on column public.booking_offers.slots is 'SAFE: the offered times (dates and HH:MM), no personal data. CLEAN-EXEMPT: generated by the database';
create index booking_offers_keyset_idx on public.booking_offers (tenant_id, created_at, id);
create index booking_offers_lead_idx on public.booking_offers (tenant_id, lead_id, created_at desc);
create index booking_offers_visit_idx on public.booking_offers (tenant_id, for_visit) where for_visit is not null;
alter table public.booking_offers enable row level security;
alter table public.booking_offers force row level security;
revoke all on public.booking_offers from public, anon, authenticated;
create trigger booking_offers_forbid_tenant_id_change before update on public.booking_offers for each row execute function app.forbid_tenant_id_change();
create trigger audit_booking_offers after insert or update or delete on public.booking_offers for each row execute function app.audit_row_change('booking_offers');
-- (members may read the times that were offered; nobody writes directly: only the functions below)
grant select on public.booking_offers to authenticated;
create policy booking_offers_select on public.booking_offers for select to authenticated using (tenant_id = any (((select app.my_tenant_ids()))::uuid[]));

