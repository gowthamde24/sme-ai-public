-- ---------------------------------------------------------------------------------------------------------------------------------
-- confirmation on booking: a visit the assistant booked is confirmed and its message queued
-- ---------------------------------------------------------------------------------------------------------------------------------
create function public.scheduler_due_confirmations(p_tenant_id uuid, p_limit integer default 50) returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := app.outbox_now();
begin
  if not app.is_scheduler() or p_tenant_id is null then
    perform app.scheduler_error('deny');
  end if;
  if p_limit is null or p_limit not between 1 and 200 then
    perform app.scheduler_error('invalid');
  end if;
  if not app.scheduler_tenant_on(p_tenant_id) or app.outbox_in_quiet_hours(v_now, p_tenant_id) then
    return '[]'::jsonb;
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object('visit_id', v.id, 'starts_at', v.starts_at, 'language', coalesce(v.language, 'en')) order by v.starts_at, v.id)
      from (select * from public.store_visits x
             where x.tenant_id = p_tenant_id and x.source = 'assistant' and x.status = 'booked' and x.starts_at > v_now + interval '10 minutes' and x.confirmed_for is distinct from x.starts_at
             order by x.starts_at, x.id limit p_limit) v
  ), '[]'::jsonb);
end;
$$;
revoke all on function public.scheduler_due_confirmations(uuid, integer) from public, anon;
grant execute on function public.scheduler_due_confirmations(uuid, integer) to authenticated;

create function public.scheduler_confirm_booking(p_tenant_id uuid, p_visit_id uuid, p_message_id uuid, p_body text, p_language text, p_uncertain boolean default false) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_now timestamptz := app.outbox_now();
  m     public.store_visits;
  v_r   jsonb;
begin
  if not app.is_scheduler() or p_tenant_id is null or p_visit_id is null or p_message_id is null then
    perform app.scheduler_error('deny');
  end if;
  if not app.scheduler_tenant_on(p_tenant_id) then
    return jsonb_build_object('status', 'skipped', 'reason', 'off');
  end if;
  perform pg_advisory_xact_lock(hashtextextended('visit-confirm:' || p_visit_id::text, 0));
  select * into m from public.store_visits x where x.id = p_visit_id and x.tenant_id = p_tenant_id for update;
  if not found then
    perform app.scheduler_error('reference');
  end if;
  if m.source <> 'assistant' or m.status <> 'booked' or m.confirmed_for is not distinct from m.starts_at or m.starts_at <= v_now then
    return jsonb_build_object('status', 'skipped', 'reason', 'not_due');
  end if;
  update public.store_visits set status = 'confirmed', confirmed_at = v_now, updated_by = v_uid where id = m.id;
  v_r := app.outbox_submit_core(v_uid, p_message_id, p_tenant_id, m.lead_id, 'whatsapp', p_body, p_language, 'visit', 'system', false, coalesce(p_uncertain, false));
  update public.store_visits set confirmation_message_id = p_message_id, confirmed_for = m.starts_at, updated_by = v_uid where id = m.id;
  return jsonb_build_object('status', 'queued', 'message_id', p_message_id, 'message', v_r);
end;
$$;
revoke all on function public.scheduler_confirm_booking(uuid, uuid, uuid, text, text, boolean) from public, anon;
grant execute on function public.scheduler_confirm_booking(uuid, uuid, uuid, text, text, boolean) to authenticated;

-- ---------------------------------------------------------------------------------------------------------------------------------
-- the phone: the time the caller AGREED to (captured.visit_at, one of the offered slots, checked by code) is booked at once when the call is a customer's (it has a lead). A caller nobody knows yet has no
-- lead: that call stays on Today ("a caller wants to visit on ...") for a person to book, as before.
-- ---------------------------------------------------------------------------------------------------------------------------------
create function public.appointment_book_from_call(p_tenant_id uuid, p_call_id uuid, p_visit_id uuid) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := auth.uid();
  v_now     timestamptz := app.visit_now();
  c         public.phone_calls;
  v_at      timestamptz;
  v_date    date;
  v_start   text;
  v_lead    public.leads;
  v_contact public.contacts;
  v_slot    record;
  v_old     public.store_visits;
  m         public.store_visits;
begin
  if not app.is_scheduler() then
    perform app.visit_error('deny');
  end if;
  if p_tenant_id is null or p_call_id is null or p_visit_id is null then
    perform app.visit_error('invalid');
  end if;
  if not app.appointment_assistant_may(p_tenant_id) then
    return jsonb_build_object('status', 'off');
  end if;
  select * into v_old from public.store_visits x where x.id = p_visit_id;
  if found then
    if v_old.tenant_id <> p_tenant_id then
      perform app.visit_error('conflict');
    end if;
    return jsonb_build_object('status', 'booked', 'visit_id', v_old.id, 'starts_at', v_old.starts_at, 'replayed', true);
  end if;
  select * into c from public.phone_calls x where x.id = p_call_id and x.tenant_id = p_tenant_id;
  if not found then
    perform app.visit_error('reference');
  end if;
  if c.captured is null or (c.captured ->> 'visit_at') is null or (c.captured ->> 'visit_at') !~ '^\d{4}-\d{2}-\d{2}T' then
    return jsonb_build_object('status', 'no_visit_at');
  end if;
  v_at := (c.captured ->> 'visit_at')::timestamptz;
  if c.lead_id is null then
    return jsonb_build_object('status', 'no_lead');
  end if;
  select * into v_lead from public.leads l where l.id = c.lead_id and l.tenant_id = p_tenant_id and l.archived_at is null;
  if not found then
    return jsonb_build_object('status', 'no_lead');
  end if;
  if v_lead.contact_id is not null then
    select * into v_contact from public.contacts k where k.id = v_lead.contact_id and k.tenant_id = p_tenant_id;
    if v_contact.erased_at is not null then
      return jsonb_build_object('status', 'no_lead');
    end if;
  end if;
  v_date := (v_at at time zone 'Asia/Kolkata')::date;
  v_start := to_char(v_at at time zone 'Asia/Kolkata', 'HH24:MI');
  begin
    select * into v_slot from app.visit_claim_slot(p_tenant_id, v_date, v_start, null, null);
    if exists (select 1 from public.store_visits x where x.tenant_id = p_tenant_id and x.lead_id = v_lead.id and x.starts_at = v_slot.o_starts and x.status in ('booked', 'confirmed', 'arrived')) then
      return jsonb_build_object('status', 'already');
    end if;
    insert into public.store_visits
      (id, tenant_id, lead_id, contact_id, company_id, visit_date, starts_at, ends_at, party_size, source, request_sha256, created_by, created_at, updated_by, staff_id, buffer_minutes, language)
    values
      (p_visit_id, p_tenant_id, v_lead.id, v_contact.id, v_lead.company_id, v_date, v_slot.o_starts, v_slot.o_ends, 1, 'assistant',
       encode(sha256(convert_to(concat_ws('|', 'call', p_call_id, v_at), 'UTF8')), 'hex'), v_uid, v_now, v_uid,
       v_slot.o_staff, coalesce((v_slot.o_set ->> 'buffer_minutes')::smallint, 0), case when c.language in ('en', 'te', 'hi', 'kn', 'ta', 'ml', 'mr') then c.language end)
    returning * into m;
  exception
    when exclusion_violation then
      return jsonb_build_object('status', 'taken');
    when sqlstate 'SM513' or sqlstate 'SM512' or sqlstate 'SM511' or sqlstate 'SM514' then
      return jsonb_build_object('status', 'taken');   -- the slot is gone or no longer bookable: the call stays on Today for a person
  end;
